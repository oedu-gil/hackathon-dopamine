const {chromium}=require(process.argv[2]||'playwright');
const {spawn}=require('node:child_process');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
(async()=>{
 const vite=pathToFileURL(path.resolve('site/web/node_modules/vite/dist/node/index.js')).href;
 const config={root:path.resolve('site/web'),server:{host:'127.0.0.1',port:31993,strictPort:true,fs:{allow:[process.cwd(),fs.realpathSync('site/web/node_modules')]}}};
 const server=spawn(process.execPath,['--input-type=module','-e',`import {createServer} from ${JSON.stringify(vite)};const s=await createServer(${JSON.stringify(config)});await s.listen();s.printUrls();`],{stdio:'pipe'});
 await new Promise((ok,bad)=>{server.stdout.on('data',d=>{if(d.toString().includes('Local:'))ok()});server.stderr.on('data',d=>process.stderr.write(d));server.on('exit',c=>bad(Error('Vite: '+c)))});
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
 const p=await browser.newPage({viewport:{width:1280,height:800}});let apiCalls=0;const errors=[];
 p.on('pageerror',e=>errors.push(String(e)));p.on('response',r=>{if(r.status()>=400)errors.push(r.status()+' '+r.url())});
 await p.route('**/api/**',r=>{apiCalls++;return r.fulfill({status:503,json:{erro:'API indisponível no teste'}})});
 await p.goto('http://127.0.0.1:31993/');
 await p.getByRole('link',{name:'Experimentar Guerra de Tortas'}).click();
 assert.ok(p.url().endsWith('#/experimentar/guerra-tortas'));
 await p.getByRole('button',{name:'Começar demonstração'}).click();
 await p.waitForFunction(()=>window.__phaser?.scene.getScene('GuerraTortas')?.animadorGuaxinim);
 const box=await p.locator('canvas').boundingBox();
 await p.mouse.click(box.x+box.width*.5,box.y+box.height*395/450);
 await p.waitForFunction(()=>window.__phaser.scene.getScene('GuerraTortas').jogando);
 await p.keyboard.down('Space');
 await p.waitForFunction(()=>window.__phaser.scene.getScene('GuerraTortas').temTorta,null,{timeout:15000});
 await p.keyboard.up('Space');
 await p.waitForFunction(()=>window.__phaser.scene.getScene('GuerraTortas').animador.estado==='idle');
 await p.mouse.click(box.x+box.width*.5,box.y+box.height*.65);
 await p.waitForFunction(()=>window.__phaser.scene.getScene('GuerraTortas').comidas===1,null,{timeout:10000});
 fs.mkdirSync('.playwright-mcp',{recursive:true});await p.screenshot({path:'.playwright-mcp/tortas-dentro-site.png'});
 assert.equal(apiCalls,0);assert.equal(await p.locator('canvas').count(),1);assert.deepEqual(errors,[]);
 await p.getByRole('button',{name:'Voltar ao site'}).click();
 await p.getByRole('button',{name:'Continuar jogando',exact:true}).click();
 assert.equal(await p.locator('canvas').count(),1);
 await p.getByRole('button',{name:'Voltar ao site'}).click();
 await p.getByRole('button',{name:'Voltar ao início',exact:true}).click();
 await p.getByRole('link',{name:'Experimentar Guerra de Tortas'}).waitFor();
 assert.equal(await p.locator('canvas').count(),0);
 await p.evaluate(()=>localStorage.setItem('dopamine-usuario',JSON.stringify({id:'teste',perfil:'crianca',aluno_id:'teste'})));
 await p.goto('http://127.0.0.1:31993/#/experimentar/guerra-tortas'); await p.reload();
 await p.waitForURL('**/#/crianca');
 assert.equal(await p.locator('canvas').count(),0);
 console.log('OK: início do SITE → demonstração → jogo real → defesa/lançamento/acerto → confirmação de saída → SITE. Zero chamadas API na demonstração; perfil infantil redirecionado.');
 }finally{await browser.close();server.kill()}
})().catch(e=>{console.error(e);process.exitCode=1});
